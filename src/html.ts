/** Escapes text for both element content and double-quoted attribute values. The apostrophe
 *  is included even though attributes here are double-quoted: this function is the ONLY door
 *  between audit data and the page, and a door that is only safe in the contexts its current
 *  callers happen to use is a door that will be opened somewhere else. */
export function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

