function runHtml(r: Run): string {
  let inner = esc(r.text);
  if (r.mono) inner = `<code>${inner}</code>`;
  if (r.strong) inner = `<strong>${inner}</strong>`;
  if (r.em) inner = `<em>${inner}</em>`;
  return r.href ? `<a href="${esc(r.href)}">${inner}</a>` : inner;
}

const runsHtml = (runs: Run[]): string => runs.map(runHtml).join("");

function cellHtml(c: Cell, tag: "th" | "td"): string {
  const attrs: string[] = [];
  if (tag === "th") attrs.push('scope="row"');
  if (c.align === "end") attrs.push('class="end"');
  if (c.colspan && c.colspan > 1) attrs.push(`colspan="${c.colspan}"`);
  let inner: string;
  if (c.status) {
    inner = `<span class="st st-${CLASS[c.status]}">${esc(MARK[c.status])}</span>`;
  } else {
    // An empty data cell is announced as "blank"; the em dash says "no value" out loud, and
    // is not the bare "-" the engine's own advisory rule flags.
    inner = c.text === "" ? "—" : runHtml({ text: c.text, mono: c.mono, strong: c.strong, ...(c.href ? { href: c.href } : {}) });
  }
  return `<${tag}${attrs.length ? ` ${attrs.join(" ")}` : ""}>${inner}</${tag}>`;
}

function blockHtml(b: Block): string[] {
  switch (b.kind) {
    case "heading":
      return [`<h${b.level}${b.id ? ` id="${esc(b.id)}"` : ""}>${esc(b.text)}</h${b.level}>`];
    case "para":
      return [`<p>${runsHtml(b.runs)}</p>`];
    case "note":
      return [`<div class="note${b.tone === "warn" ? " warn" : ""}">${runsHtml(b.runs)}</div>`];
    case "list":
      return [`<ul class="body">${b.items.map((i) => `<li>${runsHtml(i)}</li>`).join("")}</ul>`];
    case "figure":
      return [`<figure><img src="${esc(b.src)}" alt="${esc(b.alt)}">${b.caption ? `<figcaption>${esc(b.caption)}</figcaption>` : ""}</figure>`];
    case "details":
      return [`<details open><summary>${esc(b.summary)}</summary>`, ...b.blocks.flatMap(blockHtml), "</details>"];
    case "table": {
      const out: string[] = ['<div class="tw">', "<table>", `<caption>${esc(b.caption)}</caption>`, "<thead><tr>"];
      for (const col of b.columns) out.push(`<th scope="col"${col.align === "end" ? ' class="end"' : ""}>${esc(col.text)}</th>`);
      out.push("</tr></thead><tbody>");
      for (const row of b.rows) {
        // A row whose only cell spans the table is a GROUP heading (a WCAG guideline, an RGAA
        // theme). Emitted as <th scope="colgroup">, not as a <td> with empty siblings: empty
        // data cells are announced as "blank", and this row is a label, not data.
        const group = row.length === 1 && (row[0]?.colspan ?? 0) > 1;
        if (group) {
          const c = row[0]!;
          out.push(`<tr class="group"><th scope="colgroup" colspan="${c.colspan}">${esc(c.text)}</th></tr>`);
          continue;
        }
        out.push(`<tr>${row.map((c, i) => cellHtml(c, i === 0 || c.header ? "th" : "td")).join("")}</tr>`);
      }
      out.push("</tbody></table>", "</div>");
      return out;
    }
  }
}

/** The whole page. Self-contained by construction: the stylesheet is inline, there is no
 *  script, and every `src`/`href` a caller passes in is its own responsibility to keep
 *  inside the artifact (src/html-emit.ts enforces that). */
export function renderHtmlDocument(doc: Doc): string {
  const t = T[doc.lang];
  const out: string[] = [];
  out.push(`<!doctype html>`, `<html lang="${doc.lang}">`, "<head>");
  out.push('<meta charset="utf-8">', '<meta name="viewport" content="width=device-width, initial-scale=1">');
  out.push(`<title>${esc(doc.title)}</title>`);
  out.push(`<style>${STYLE}</style>`);
  out.push("</head>", "<body>");
  out.push(`<a class="skip" href="#content">${esc(t.skip)}</a>`);
  out.push('<header class="top"><div class="wrap">');
  out.push(`<h1>${esc(doc.title)}</h1>`);
  if (doc.subtitle?.length) out.push(`<p class="sub">${runsHtml(doc.subtitle)}</p>`);
  if (doc.nav?.length) {
    out.push(`<nav class="docs" aria-label="${esc(t.nav)}"><ul>`);
    for (const l of doc.nav) out.push(`<li><a href="${esc(l.href)}"${l.current ? ' aria-current="page"' : ""}>${esc(l.text)}</a></li>`);
    out.push("</ul></nav>");
  }
  out.push("</div></header>");
  out.push('<main id="content" class="wrap">');
  for (const b of doc.blocks) out.push(...blockHtml(b));
  out.push("</main>");
  out.push(`<footer class="bot"><div class="wrap"><p>${esc(t.generated)} · ${esc(t.printHint)}</p></div></footer>`);
  out.push("</body>", "</html>");
  return `${out.join("\n")}\n`;
}
