// THE HTML RENDERER — a document model, and the one place that turns it into a page.
//
// This module knows NOTHING about an audit. It takes a `Doc` — headings, paragraphs, notes,
// tables, figures — and returns a string. Everything that decides what a criterion's status
// IS lives in src/html-report.ts, which builds the `Doc`; everything that touches the disk
// lives in src/html-emit.ts. The split is what lets the renderer be tested by rendering.
//
// Three rules hold it together:
//
//   1. NO MARKDOWN CONVERSION. A GFM table cannot express `<caption>` or `scope=`, and a
//      report whose own tables have no headers is an accessibility deliverable that fails
//      1.3.1. So the model is structural and the renderer emits real table markup.
//   2. NO `<script>`, EVER. The artifact is downloaded and opened from a file:// URL or an
//      artifact viewer, both of which are hostile to scripts, and a report that needs
//      JavaScript to be read is a report that some readers cannot read.
//   3. THE PAGE MUST PASS THIS ENGINE'S OWN AUDIT. Landmarks, one `<h1>`, no heading-level
//      skip, `<caption>` and `scope` on every table, a skip link whose target exists, `lang`
//      from the document, and status NEVER encoded by colour alone — every mark carries its
//      letter. tests/html.test.ts audits the output with the engine rather than asserting
//      that it looks right.
import { NEUTRAL_THEME, type Theme } from "./theme.js";
import type { Lang, Status } from "./types.js";

/** The status marks, identical to the Markdown grids — `C` conforming, `NC` non-conforming,
 *  `—` not applicable, `?` to assess. The LETTER is the accessible channel; the colour below
 *  is redundant, which is what keeps this page from failing 1.4.1 itself. */
const MARK: Record<Status, string> = { C: "C", NC: "NC", NA: "—", manual: "?" };
const CLASS: Record<Status, string> = { C: "c", NC: "nc", NA: "na", manual: "m" };

export type Tone = "info" | "warn";
export type Align = "start" | "end";

/** An inline span. Composing runs is how emphasis and code get expressed without a Markdown
 *  parser — and without any path by which raw HTML could reach the output. */
export interface Run {
  text: string;
  mono?: boolean;
  strong?: boolean;
  em?: boolean;
  href?: string;
}

export interface Cell {
  text: string;
  mono?: boolean;
  /** Rendered as its mark plus a colour class. Never a colour on its own. */
  status?: Status;
  align?: Align;
  strong?: boolean;
  colspan?: number;
  /** A row header — `<th scope="row">` rather than `<td>`. */
  header?: boolean;
  href?: string;
}

export interface Column {
  text: string;
  align?: Align;
}

export type Block =
  // Level 1 is the document title and is emitted by the chrome, never by a block: a `Doc`
  // that could contain a second <h1> is a `Doc` that will eventually contain one.
  | { kind: "heading"; level: 2 | 3 | 4; text: string; id?: string }
  | { kind: "para"; runs: Run[] }
  | { kind: "note"; tone: Tone; runs: Run[] }
  | { kind: "list"; items: Run[][] }
  | { kind: "table"; caption: string; columns: Column[]; rows: Cell[][] }
  | { kind: "figure"; src: string; alt: string; caption?: string }
  | { kind: "details"; summary: string; blocks: Block[] };

export interface NavLink {
  href: string;
  text: string;
  current?: boolean;
}

export interface Doc {
  lang: Lang;
  /** The `<title>` and the single `<h1>`. */
  title: string;
  subtitle?: Run[];
  /** Sibling documents. Rendered as a NAMED `<nav>` — two unnamed navigation regions on one
   *  page is RGAA 12.6, which this engine reports. */
  nav?: NavLink[];
  /** The nav's accessible name. Defaults to « Documents du rapport »: the results server
   *  (src/serve.ts) names its own navigation, which is not a list of report documents. */
  navLabel?: string;
  blocks: Block[];
}

const T = {
  fr: {
    skip: "Aller au contenu",
    nav: "Documents du rapport",
    printHint: "Pour un PDF : imprimez cette page (Ctrl/Cmd + P) et choisissez « Enregistrer au format PDF ».",
    generated: "Généré par ultra11y",
    skipNav: "Accès rapide",
    service: "Audit d'accessibilité",
    tagline: "Rapport généré par ultra11y",
  },
  en: {
    skip: "Skip to content",
    nav: "Report documents",
    printHint: "For a PDF: print this page (Ctrl/Cmd + P) and choose “Save as PDF”.",
    generated: "Generated by ultra11y",
    skipNav: "Quick access",
    service: "Accessibility audit",
    tagline: "Report generated by ultra11y",
  },
} as const;

/** The class vocabulary of one markup flavour. The STRUCTURE (elements, `scope`, captions,
 *  landmarks, letters) is emitted by the same code for both; only these names change. */
interface Skin {
  /** On every table cell. */
  cell: string;
  end: string;
  group: string;
  status: (s: Status) => string;
  note: (tone: Tone) => { open: string; close: string };
  list: string;
  table: { open: string[]; close: string[] };
  figure: string;
  figcaption: string;
  details: string;
}

const NEUTRAL_SKIN: Skin = {
  cell: "",
  end: "end",
  group: "group",
  status: (s) => `st st-${CLASS[s]}`,
  note: (tone) => ({ open: `<div class="note${tone === "warn" ? " warn" : ""}">`, close: "</div>" }),
  list: "body",
  table: { open: ['<div class="tw">', "<table>"], close: ["</table>", "</div>"] },
  figure: "",
  figcaption: "",
  details: "",
};

/** DSFR badges by status. The badge's icon is switched off (`fr-badge--no-icon`): DSFR draws it
 *  from an SVG file the inlined stylesheet cannot reach, and the letter is the channel anyway. */
const DSFR_BADGE: Record<Status, string> = { C: "fr-badge--success", NC: "fr-badge--error", NA: "", manual: "fr-badge--warning" };

const DSFR_SKIN: Skin = {
  // DSFR cells do not wrap by default; a criterion title in one line would push the status
  // column off screen (and reflow, 1.4.10, is exactly what this page must not fail).
  cell: "fr-cell--multiline",
  end: "fr-cell--right",
  group: "u11y-group",
  status: (s) => `fr-badge fr-badge--sm fr-badge--no-icon${DSFR_BADGE[s] ? ` ${DSFR_BADGE[s]}` : ""}`,
  // A warning is an alert (small variant, no title); anything else is a callout.
  note: (tone) =>
    tone === "warn"
      ? { open: '<div class="fr-alert fr-alert--warning fr-alert--sm fr-mb-3w"><p>', close: "</p></div>" }
      : { open: '<div class="fr-callout fr-mb-3w"><p class="fr-callout__text">', close: "</p></div>" },
  list: "",
  table: {
    open: [
      '<div class="fr-table fr-table--bordered">',
      '<div class="fr-table__wrapper">',
      '<div class="fr-table__container">',
      '<div class="fr-table__content">',
      "<table>",
    ],
    close: ["</table>", "</div>", "</div>", "</div>", "</div>"],
  },
  figure: "fr-content-media",
  figcaption: "fr-content-media__caption",
  details: "u11y-details",
};

const cls = (c: string): string => (c ? ` class="${c}"` : "");
const cellCls = (skin: Skin, end: boolean): string => cls([skin.cell, end ? skin.end : ""].filter(Boolean).join(" "));

/** Escapes text for both element content and double-quoted attribute values. The apostrophe
 *  is included even though attributes here are double-quoted: this function is the ONLY door
 *  between audit data and the page, and a door that is only safe in the contexts its current
 *  callers happen to use is a door that will be opened somewhere else. */
export function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

function runHtml(r: Run): string {
  let inner = esc(r.text);
  if (r.mono) inner = `<code>${inner}</code>`;
  if (r.strong) inner = `<strong>${inner}</strong>`;
  if (r.em) inner = `<em>${inner}</em>`;
  return r.href ? `<a href="${esc(r.href)}">${inner}</a>` : inner;
}

const runsHtml = (runs: Run[]): string => runs.map(runHtml).join("");

function cellHtml(c: Cell, tag: "th" | "td", skin: Skin): string {
  const attrs: string[] = [];
  if (tag === "th") attrs.push('scope="row"');
  const klass = cellCls(skin, c.align === "end").trim();
  if (klass) attrs.push(klass);
  if (c.colspan && c.colspan > 1) attrs.push(`colspan="${c.colspan}"`);
  let inner: string;
  if (c.status) {
    inner = `<span class="${skin.status(c.status)}">${esc(MARK[c.status])}</span>`;
  } else {
    // An empty data cell is announced as "blank"; the em dash says "no value" out loud, and
    // is not the bare "-" the engine's own advisory rule flags.
    inner = c.text === "" ? "—" : runHtml({ text: c.text, mono: c.mono, strong: c.strong, ...(c.href ? { href: c.href } : {}) });
  }
  return `<${tag}${attrs.length ? ` ${attrs.join(" ")}` : ""}>${inner}</${tag}>`;
}

function blockHtml(b: Block, skin: Skin): string[] {
  switch (b.kind) {
    case "heading":
      return [`<h${b.level}${b.id ? ` id="${esc(b.id)}"` : ""}>${esc(b.text)}</h${b.level}>`];
    case "para":
      return [`<p>${runsHtml(b.runs)}</p>`];
    case "note": {
      const n = skin.note(b.tone);
      return [`${n.open}${runsHtml(b.runs)}${n.close}`];
    }
    case "list":
      return [`<ul${cls(skin.list)}>${b.items.map((i) => `<li>${runsHtml(i)}</li>`).join("")}</ul>`];
    case "figure":
      // A captioned image is tied to its caption the way RGAA 1.9.1 asks: `role="figure"` and
      // an `aria-label` repeating the caption. Without them the engine's own rule flags every
      // illustrated crop and component snapshot this renderer draws.
      return [
        `<figure${cls(skin.figure)}${b.caption ? ` role="figure" aria-label="${esc(b.caption)}"` : ""}><img src="${esc(b.src)}" alt="${esc(b.alt)}">${b.caption ? `<figcaption${cls(skin.figcaption)}>${esc(b.caption)}</figcaption>` : ""}</figure>`,
      ];
    case "details":
      return [`<details${cls(skin.details)} open><summary>${esc(b.summary)}</summary>`, ...b.blocks.flatMap((x) => blockHtml(x, skin)), "</details>"];
    case "table": {
      const out: string[] = [...skin.table.open, `<caption>${esc(b.caption)}</caption>`, "<thead><tr>"];
      for (const col of b.columns) out.push(`<th scope="col"${cellCls(skin, col.align === "end")}>${esc(col.text)}</th>`);
      out.push("</tr></thead><tbody>");
      for (const row of b.rows) {
        // A row whose only cell spans the table is a GROUP heading (a WCAG guideline, an RGAA
        // theme). Emitted as <th scope="colgroup">, not as a <td> with empty siblings: empty
        // data cells are announced as "blank", and this row is a label, not data.
        const group = row.length === 1 && (row[0]?.colspan ?? 0) > 1;
        if (group) {
          const c = row[0]!;
          out.push(`<tr class="${skin.group}"><th scope="colgroup" colspan="${c.colspan}"${cellCls(skin, false)}>${esc(c.text)}</th></tr>`);
          continue;
        }
        out.push(`<tr>${row.map((c, i) => cellHtml(c, i === 0 || c.header ? "th" : "td", skin)).join("")}</tr>`);
      }
      const [first = "", ...rest] = skin.table.close;
      out.push(`</tbody>${first}`, ...rest);
      return out;
    }
  }
}

/** The whole page. Self-contained by construction: the stylesheet is inline, there is no
 *  script, and every `src`/`href` a caller passes in is its own responsibility to keep
 *  inside the artifact (src/html-emit.ts enforces that). The look comes from `theme`
 *  (src/theme.ts): its stylesheet, and the class vocabulary of its `markup` flavour. The
 *  accessible structure — skip link, landmarks, one h1, captioned tables with `scope`, status
 *  letters, `lang` — is emitted identically for every theme. */
export function renderHtmlDocument(doc: Doc, theme: Theme = NEUTRAL_THEME): string {
  return theme.markup === "dsfr" ? renderDsfr(doc, theme) : renderNeutral(doc, theme);
}

function pageHead(doc: Doc, theme: Theme): string[] {
  const out: string[] = [];
  out.push(`<!doctype html>`, `<html lang="${doc.lang}">`, "<head>");
  out.push('<meta charset="utf-8">', '<meta name="viewport" content="width=device-width, initial-scale=1">');
  out.push(`<title>${esc(doc.title)}</title>`);
  out.push(`<style>${theme.css}</style>`);
  if (theme.printCss) out.push(`<style media="print">${theme.printCss}</style>`);
  out.push("</head>", "<body>");
  return out;
}

/** DSFR markup: skip links, a simple header WITHOUT the bloc-marque (ultra11y cannot know the
 *  issuing administration, and the Marianne block is not ours to draw), the content in an
 *  `fr-container`, a simple footer. No DSFR JavaScript: every component used here works
 *  without it, and `<details>` stays native rather than a JS-driven accordion. */
function renderDsfr(doc: Doc, theme: Theme): string {
  const t = T[doc.lang];
  const out = pageHead(doc, theme);
  out.push(
    `<div class="fr-skiplinks"><nav class="fr-container" aria-label="${esc(t.skipNav)}"><ul class="fr-skiplinks__list"><li><a class="fr-link" href="#content">${esc(t.skip)}</a></li></ul></nav></div>`,
  );
  out.push('<header class="fr-header">', '<div class="fr-header__body"><div class="fr-container"><div class="fr-header__body-row">');
  out.push(
    `<div class="fr-header__service"><p class="fr-header__service-title">${esc(t.service)}</p><p class="fr-header__service-tagline">${esc(t.tagline)}</p></div>`,
  );
  out.push("</div></div></div>");
  if (doc.nav?.length) {
    out.push(`<div class="fr-container"><nav class="u11y-docs fr-pb-2w" aria-label="${esc(doc.navLabel ?? t.nav)}"><ul class="fr-tags-group">`);
    for (const l of doc.nav) out.push(`<li><a class="fr-tag" href="${esc(l.href)}"${l.current ? ' aria-current="page"' : ""}>${esc(l.text)}</a></li>`);
    out.push("</ul></nav></div>");
  }
  out.push("</header>");
  out.push('<main id="content" class="fr-container fr-pt-4w fr-pb-6w">');
  out.push(`<h1>${esc(doc.title)}</h1>`);
  if (doc.subtitle?.length) out.push(`<p class="fr-text--lead">${runsHtml(doc.subtitle)}</p>`);
  for (const b of doc.blocks) out.push(...blockHtml(b, DSFR_SKIN));
  out.push("</main>");
  out.push(
    `<footer class="fr-footer"><div class="fr-container"><div class="fr-footer__body"><div class="fr-footer__content"><p class="fr-footer__content-desc">${esc(t.generated)} · ${esc(t.printHint)}</p></div></div></div></footer>`,
  );
  out.push("</body>", "</html>");
  return `${out.join("\n")}\n`;
}

function renderNeutral(doc: Doc, theme: Theme): string {
  const t = T[doc.lang];
  const out = pageHead(doc, theme);
  out.push(`<a class="skip" href="#content">${esc(t.skip)}</a>`);
  out.push('<header class="top"><div class="wrap">');
  out.push(`<h1>${esc(doc.title)}</h1>`);
  if (doc.subtitle?.length) out.push(`<p class="sub">${runsHtml(doc.subtitle)}</p>`);
  if (doc.nav?.length) {
    out.push(`<nav class="docs" aria-label="${esc(doc.navLabel ?? t.nav)}"><ul>`);
    for (const l of doc.nav) out.push(`<li><a href="${esc(l.href)}"${l.current ? ' aria-current="page"' : ""}>${esc(l.text)}</a></li>`);
    out.push("</ul></nav>");
  }
  out.push("</div></header>");
  out.push('<main id="content" class="wrap">');
  for (const b of doc.blocks) out.push(...blockHtml(b, NEUTRAL_SKIN));
  out.push("</main>");
  out.push(`<footer class="bot"><div class="wrap"><p>${esc(t.generated)} · ${esc(t.printHint)}</p></div></footer>`);
  out.push("</body>", "</html>");
  return `${out.join("\n")}\n`;
}
