// THE HTML RENDERER — a document model, and the one place that turns it into a page.
//
// This module knows NOTHING about an audit. It takes a `Doc` — headings, paragraphs, notes,
// tables, figures — and returns a string. Everything that decides what a criterion's status
// IS lives in src/html-report.ts, which builds the `Doc`; everything that touches the disk
// lives in src/html-emit.ts. The split is what lets the renderer be tested by rendering.
//
// Three rules hold it together:
//
//   1. NO MARKDOWN CONVERSION. A GFM table cannot express `<caption>` or `scope=`, and a
//      report whose own tables have no headers is an accessibility deliverable that fails
//      1.3.1. So the model is structural and the renderer emits real table markup.
//   2. NO `<script>`, EVER. The artifact is downloaded and opened from a file:// URL or an
//      artifact viewer, both of which are hostile to scripts, and a report that needs
//      JavaScript to be read is a report that some readers cannot read.
//   3. THE PAGE MUST PASS THIS ENGINE'S OWN AUDIT. Landmarks, one `<h1>`, no heading-level
//      skip, `<caption>` and `scope` on every table, a skip link whose target exists, `lang`
//      from the document, and status NEVER encoded by colour alone — every mark carries its
//      letter. tests/html.test.ts audits the output with the engine rather than asserting
//      that it looks right.
import type { Lang, Status } from "./types.js";

/** The status marks, identical to the Markdown grids — `C` conforming, `NC` non-conforming,
 *  `—` not applicable, `?` to assess. The LETTER is the accessible channel; the colour below
 *  is redundant, which is what keeps this page from failing 1.4.1 itself. */
const MARK: Record<Status, string> = { C: "C", NC: "NC", NA: "—", manual: "?" };
const CLASS: Record<Status, string> = { C: "c", NC: "nc", NA: "na", manual: "m" };

export type Tone = "info" | "warn";
export type Align = "start" | "end";

/** An inline span. Composing runs is how emphasis and code get expressed without a Markdown
 *  parser — and without any path by which raw HTML could reach the output. */
export interface Run {
  text: string;
  mono?: boolean;
  strong?: boolean;
  em?: boolean;
  href?: string;
}

export interface Cell {
  text: string;
  mono?: boolean;
  /** Rendered as its mark plus a colour class. Never a colour on its own. */
  status?: Status;
  align?: Align;
  strong?: boolean;
  colspan?: number;
  /** A row header — `<th scope="row">` rather than `<td>`. */
  header?: boolean;
  href?: string;
}

export interface Column {
  text: string;
  align?: Align;
}

export type Block =
  // Level 1 is the document title and is emitted by the chrome, never by a block: a `Doc`
  // that could contain a second <h1> is a `Doc` that will eventually contain one.
  | { kind: "heading"; level: 2 | 3 | 4; text: string; id?: string }
  | { kind: "para"; runs: Run[] }
  | { kind: "note"; tone: Tone; runs: Run[] }
  | { kind: "list"; items: Run[][] }
  | { kind: "table"; caption: string; columns: Column[]; rows: Cell[][] }
  | { kind: "figure"; src: string; alt: string; caption?: string }
  | { kind: "details"; summary: string; blocks: Block[] };

export interface NavLink {
  href: string;
  text: string;
  current?: boolean;
}

export interface Doc {
  lang: Lang;
  /** The `<title>` and the single `<h1>`. */
  title: string;
  subtitle?: Run[];
  /** Sibling documents. Rendered as a NAMED `<nav>` — two unnamed navigation regions on one
   *  page is RGAA 12.6, which this engine reports. */
  nav?: NavLink[];
  blocks: Block[];
}

