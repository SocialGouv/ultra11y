// UNIT-TEST SNAPSHOT FILES as an audit source — Jest / Vitest `__snapshots__/*.snap`.
//
// A project's unit tests already render every component, and a snapshot file is where that
// render was written down: real host markup, the output a design system (DSFR, MUI…) actually
// produced, not the JSX call that asked for it. Reading it costs the project nothing — no test
// run, no browser, no harness — so a `.snap` in scope is audited like any other capture.
//
// FORMAT. A `.snap` is a CommonJS module of template literals:
//   exports[`Button renders 1`] = `
//   <div>
//     <button
//       class="x"
//     >
//       Label
//     </button>
//   </div>
//   `;
// Jest/Vitest escape exactly three things in both the key and the value (printBacktickString):
// a backtick, a backslash and `${`, each with a leading backslash. Nothing else is escaped, so
// "backslash + next character → that character" is the whole inverse.
//
// WHAT COUNTS AS MARKUP. An entry is audited only when its value is host markup:
//   • the pretty-format DOM serialisation (`container`, `asFragment()` → `<DocumentFragment>`),
//   • react-test-renderer's `toJSON()` (`className="x"`, `onClick={[Function]}`),
//   • a string snapshot whose content is HTML (`expect(container.innerHTML).toMatchSnapshot()`).
// Objects, arrays, numbers and prose strings are not markup and are skipped — counted, never
// guessed at. So is a tree carrying a Capitalised element (a shallow render: `<Button>` is the
// component CALL, and lowercasing it would audit it as a native <button> it may never render).
//
// ANCHORING. One Doc per entry, its `file` the `.snap` itself. The converted markup is padded
// with the newlines that precede it in the file, and every rewrite keeps its newlines, so a
// finding's LINE is the `.snap` line the element is written on. The byte offsets are not the
// file's (`className=` became `class=`), which is what `lossy` says: `fix` never edits a
// snapshot by range — and a snapshot is regenerated by the test runner anyway.
//
// SCOPE OF THE CLAIM. A unit-test render is a COMPONENT, never a page: an `<html>` wrapper is
// dropped so the page-scoped rules (title, lang, viewport) stay off, exactly as for a component
// capture. And it was rendered by jsdom/happy-dom, not a browser: no computed style, no layout,
// so the rendering criteria (contrast, reflow, focus visibility) stay « à évaluer ».
import { basename, dirname, join } from "node:path";
import { type Doc, lineColAt, lineStartsOf, parseHtml } from "./html.js";
import { normAttrName } from "./jsx-bridge.js";
import { sourceForTest } from "../capture.js";

/** Is this a Jest/Vitest snapshot file? */
export function isUnitSnapshotFile(file: string): boolean {
  return /\.snap$/i.test(file);
}

export interface SnapshotEntry {
  /** The entry's key, unescaped — `Button > renders the primary variant 1`. */
  name: string;
  /** 1-based line of the `exports[` the entry starts on. */
  line: number;
  /** The value, unescaped, starting with whatever followed the opening backtick. */
  value: string;
  /** 1-based line the value's first character sits on (the opening backtick's line). */
  valueLine: number;
}

/** Read the backtick literal opening at `start` (the backtick itself). Returns the raw body and
 *  the index just past the closing backtick, or undefined when the literal never closes. */
function readTemplate(src: string, start: number): { body: string; end: number } | undefined {
  let i = start + 1;
  while (i < src.length) {
    const c = src[i];
    if (c === "\\") {
      i += 2;
      continue;
    }
    if (c === "`") return { body: src.slice(start + 1, i), end: i + 1 };
    i++;
  }
  return undefined;
}

const unescapeTemplate = (s: string): string => s.replace(/\\([\s\S])/g, "$1");

/** Every `exports[`key`] = `value`;` entry of a snapshot file, in file order. A file that is not
 *  in this format (another tool's `.snap`) yields none. */
export function parseSnapshotEntries(src: string): SnapshotEntry[] {
  const out: SnapshotEntry[] = [];
  const head = /^exports\[`/gm;
  const starts = lineStartsOf(src);
  const lineOf = (offset: number): number => lineColAt(starts, offset).line;
  for (let m = head.exec(src); m; m = head.exec(src)) {
    const keyTpl = readTemplate(src, m.index + "exports[".length);
    if (!keyTpl) break;
    const eq = /^\]\s*=\s*`/.exec(src.slice(keyTpl.end, keyTpl.end + 16));
    if (!eq) continue;
    const valueStart = keyTpl.end + eq[0].length - 1;
    const valTpl = readTemplate(src, valueStart);
    if (!valTpl) break;
    const entryLine = lineOf(m.index);
    const valueLine = lineOf(valueStart);
    out.push({ name: unescapeTemplate(keyTpl.body), line: entryLine, value: unescapeTemplate(valTpl.body), valueLine });
    head.lastIndex = valTpl.end;
  }
  return out;
}

// ---- markup detection + conversion -------------------------------------------------------

const VOID = new Set(["area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"]);
/** Wrappers that are not elements of the render: the fragment `asFragment()` returns, and the
 *  document element — a unit-test render is a component, never the page. */
const UNWRAP = new Set(["DocumentFragment", "html"]);

const newlinesOf = (s: string): string => s.replace(/[^\n]/g, "");

/** `"display": "none", "fontSize": 12` → `display:none;font-size:12` — the simple, flat style
 *  objects react-test-renderer prints. Anything nested is ignored rather than guessed. */
function styleObjectToCss(body: string): string {
  const decls: string[] = [];
  for (const m of body.matchAll(/"([\w-]+)":\s*(?:"([^"]*)"|(-?\d+(?:\.\d+)?))/g)) {
    const prop = (m[1] as string).replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
    decls.push(`${prop}:${m[2] ?? m[3]}`);
  }
  return decls.join(";");
}

/** Convert one `{…}` prop value (react-test-renderer) to an HTML attribute value, or undefined
 *  to drop the prop. Only what HTML can carry survives: a function, an object, an element passed
 *  as a prop — none of that reaches the DOM, so none of it may reach the audit. */
function braceValue(name: string, inner: string): string | undefined {
  const v = inner.trim();
  const stringy = /^(?:aria-|data-)/.test(name);
  if (v === "true") return stringy ? "true" : "";
  if (v === "false") return stringy ? "false" : undefined;
  if (/^-?\d+(?:\.\d+)?$/.test(v)) return v;
  if (/^"[^"]*"$/.test(v)) return v.slice(1, -1);
  if (name === "style" && /^Object\s*\{[\s\S]*\}$|^\{[\s\S]*\}$/.test(v)) return styleObjectToCss(v) || undefined;
  return undefined;
}

const escAttr = (s: string): string => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;");

/** Why an entry is not audited, or undefined when it is markup. */
export type SkipReason = "not-markup" | "component-tree";

/** Turn a pretty-format / react-test-renderer serialisation into HTML the engine parses,
 *  keeping every newline where it was — or why it is not host markup. */
export function snapshotMarkupToHtml(value: string): { html: string } | { skip: SkipReason } {
  let text = value;
  const trimmed = value.trim();
  // A string snapshot (`"<div>…</div>"`) whose content is HTML. The quotes are replaced by
  // spaces so the content keeps its lines; pretty-format escapes nothing else in a string
  // under the snapshot defaults, and `\"` is the one escape an older `escapeString` adds.
  if (trimmed.startsWith('"') && trimmed.endsWith('"') && trimmed.length >= 2) {
    const inner = trimmed.slice(1, -1).replace(/\\(["\\])/g, "$1");
    if (!/^<[A-Za-z!]/.test(inner.trim()) || !inner.trim().endsWith(">")) return { skip: "not-markup" };
    const at = value.indexOf(trimmed);
    // Same rule as the serialized tree below: a unit-test render is never the page.
    const component = inner.replace(/<!doctype[^>]*>|<\/?html\b[^>]*>/gi, "");
    text = `${value.slice(0, at)} ${component}`;
    return { html: text };
  }
  if (!/^<[A-Za-z]/.test(trimmed) || !trimmed.endsWith(">")) return { skip: "not-markup" };

  let out = "";
  let i = 0;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    if (c !== "<") {
      out += c;
      i++;
      continue;
    }
    if (text.startsWith("<!--", i)) {
      const end = text.indexOf("-->", i + 4);
      const stop = end === -1 ? n : end + 3;
      out += text.slice(i, stop);
      i = stop;
      continue;
    }
    const close = /^<\/([A-Za-z][\w:.-]*)\s*>/.exec(text.slice(i, i + 200));
    if (close) {
      out += UNWRAP.has(close[1] as string) ? newlinesOf(close[0]) : close[0];
      i += close[0].length;
      continue;
    }
    const open = /^<([A-Za-z][\w:.-]*)/.exec(text.slice(i, i + 200));
    if (!open) {
      out += c;
      i++;
      continue;
    }
    const tag = open[1] as string;
    if (/^[A-Z]/.test(tag) && tag !== "DocumentFragment") return { skip: "component-tree" };
    const unwrap = UNWRAP.has(tag);
    i += open[0].length;
    let attrs = "";
    let selfClosing = false;
    // pretty-format writes each attribute on its own indented line, so the separator is usually
    // already there; adding one only when it is not keeps the text close to the file's.
    const sp = (): string => (/\s$/.test(attrs) ? "" : " ");
    // Attributes, one per line in pretty-format, until `>` or `/>`.
    while (i < n) {
      const ch = text[i] as string;
      if (/\s/.test(ch)) {
        attrs += ch;
        i++;
        continue;
      }
      if (ch === ">") {
        i++;
        break;
      }
      if (ch === "/" && text[i + 1] === ">") {
        selfClosing = true;
        i += 2;
        break;
      }
      const nm = /^[^\s=/>]+/.exec(text.slice(i, i + 200));
      if (!nm) {
        i++;
        continue;
      }
      const rawName = nm[0];
      const name = normAttrName(rawName);
      i += rawName.length;
      if (text[i] !== "=") {
        attrs += `${sp()}${name}`;
        continue;
      }
      i++;
      if (text[i] === '"') {
        // A DOM attribute value; `\"` only under an older `escapeString`.
        let j = i + 1;
        while (j < n && !(text[j] === '"' && text[j - 1] !== "\\")) j++;
        const val = text.slice(i + 1, j);
        attrs += `${sp()}${name}="${escAttr(val.replace(/\\(["\\])/g, "$1"))}"${newlinesOf(val)}`;
        i = j + 1;
        continue;
      }
      if (text[i] === "{") {
        // A react-test-renderer prop: balanced braces, strings skipped over.
        let depth = 0;
        let j = i;
        for (; j < n; j++) {
          const cj = text[j];
          if (cj === '"') {
            j++;
            while (j < n && text[j] !== '"') j += text[j] === "\\" ? 2 : 1;
            continue;
          }
          if (cj === "{") depth++;
          else if (cj === "}" && --depth === 0) break;
        }
        const inner = text.slice(i + 1, j);
        const conv = braceValue(name, inner);
        attrs += conv === undefined ? newlinesOf(inner) : `${sp()}${name}="${escAttr(conv)}"${newlinesOf(inner)}`;
        i = j + 1;
        continue;
      }
      // An unquoted value — not something pretty-format writes; keep it verbatim.
      const bare = /^[^\s>]+/.exec(text.slice(i, i + 200))?.[0] ?? "";
      attrs += `${sp()}${name}=${bare}`;
      i += bare.length;
    }
    if (unwrap) {
      out += newlinesOf(attrs);
      continue;
    }
    // htmlparser2 (HTML mode) ignores `/>` on a non-void element, so `<div />` would swallow
    // its siblings: close it explicitly. A void element keeps the file's own spelling.
    out += `<${tag}${attrs}${!selfClosing ? ">" : VOID.has(tag.toLowerCase()) ? "/>" : `></${tag}>`}`;
  }
  return { html: out };
}

// ---- docs -------------------------------------------------------------------------------

export interface SnapshotDocs {
  docs: Doc[];
  /** Entries read in the file. */
  entries: number;
  /** Entries not audited, by reason. */
  skipped: { name: string; line: number; reason: SkipReason }[];
}

/** The test file a snapshot belongs to: `src/__snapshots__/Button.test.tsx.snap` →
 *  `src/Button.test.tsx`. Undefined when the path does not follow the convention. */
export function snapshotTestFile(file: string): string | undefined {
  const posix = file.split("\\").join("/");
  const dir = dirname(posix);
  if (basename(dir) !== "__snapshots__") return undefined;
  return join(dirname(dir), basename(posix).replace(/\.snap$/i, ""))
    .split("\\")
    .join("/");
}

/** Parse a snapshot file into one COMPONENT Doc per markup entry, each anchored to the `.snap`
 *  file and the entry's own lines, and carrying the entry's name in its provenance. */
export function parseUnitSnapshotFile(src: string, file: string): SnapshotDocs {
  const entries = parseSnapshotEntries(src);
  const test = snapshotTestFile(file);
  const sourceFile = sourceForTest(".", test);
  const component = sourceFile ? basename(sourceFile).replace(/\.[cm]?[jt]sx?$/i, "") : undefined;
  const docs: Doc[] = [];
  const skipped: SnapshotDocs["skipped"] = [];
  for (const e of entries) {
    const conv = snapshotMarkupToHtml(e.value);
    if ("skip" in conv) {
      skipped.push({ name: e.name, line: e.line, reason: conv.skip });
      continue;
    }
    // Pad with the lines above the value so a parsed element's line IS its line in the file.
    const doc = parseHtml("\n".repeat(e.valueLine - 1) + conv.html, file, true);
    doc.capture = {
      v: 1,
      snapshot: e.name,
      ...(test ? { test } : {}),
      ...(sourceFile ? { sourceFile } : {}),
      ...(component ? { component } : {}),
    };
    docs.push(doc);
  }
  if (docs[0]) docs[0].unitSnapshot = { skipped: skipped.length };
  return { docs, entries: entries.length, skipped };
}
